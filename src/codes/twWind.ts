export type WindNote = 'basin' | 'pengjia' | 'dongji'
const bare = (town: string) => town.replace(/（.*?）/g, '').trim()

/** 工址 鄉鎮 → 기본설계풍속 V10 (m/s). 표에 없으면 null */
export function windV10(county: string, town: string): { V10: number; note?: WindNote } | null {
  if (county === BASIN) return { V10: 42.5, note: 'basin' }
  const z = ZONES[county], name = bare(town)
  if (!z) return null
  for (const [v, towns] of Object.entries(z)) if (towns.includes(name)) {
    const note: WindNote | undefined = county === '基隆市' && name === '中正區' ? 'pengjia' : county === '澎湖縣' && name === '望安鄉' ? 'dongji' : undefined
    return { V10: +v, ...(note ? { note } : {}) }
  }
  return null
}

/** 기본설계풍속 출처 — 입력 V10 이 표 2.4 값과 같으면 'table', 다르면 'user'(표값 함께), 표에 없으면 'none' */
export type WindSource = { kind: 'table'; V10: number; note?: WindNote } | { kind: 'user'; V10: number; note?: WindNote } | { kind: 'none' }
export function windSource(V10: number, county: string, town: string): WindSource {
  const w = windV10(county, town)
  if (!w) return { kind: 'none' }
  return { kind: Math.abs(w.V10 - V10) < 1e-6 ? 'table' : 'user', V10: w.V10, ...(w.note ? { note: w.note } : {}) }
}
